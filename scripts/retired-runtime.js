#!/usr/bin/env node
'use strict';
/**
 * B-259: regenerate `lib/runtime-retired.js` from Git history.
 *
 * For every `lib/**.js` path that a commit on HEAD's history held and HEAD's tree no
 * longer holds, the sha256 of each blob that path ever had. `lib/runtime.js` uses the
 * table to retire an unrecorded runtime module (one older than `.managed.json`) when
 * its bytes are exactly a release of that path. Hooks are left out on purpose: a hook
 * script may still be wired in a host's settings, so hooks never retire.
 *
 *   node scripts/retired-runtime.js          print the table as JSON
 *   node scripts/retired-runtime.js --write  rewrite lib/runtime-retired.js
 *
 * Reads history through `git`, never the working tree, so a clone reproduces it.
 * `test/runtime_retired_test.js` fails when the committed table and this disagree.
 */

const crypto = require('crypto');
const fs = require('fs');
const path = require('path');
const { execFileSync } = require('child_process');

function git(dir, args, buffer) {
  return execFileSync('git', ['-C', dir].concat(args), { encoding: buffer ? 'buffer' : 'utf8', maxBuffer: 1 << 28, stdio: ['ignore', 'pipe', 'ignore'] });
}

const lines = (s) => String(s).split('\n').map((l) => l.trim()).filter(Boolean);
const isModule = (p) => /^lib\/.+\.js$/.test(p);

function generate(repoDir) {
  const live = new Set(lines(git(repoDir, ['ls-tree', '-r', '--name-only', 'HEAD', '--', 'lib'])));
  const ever = new Set(lines(git(repoDir, ['log', '--no-renames', '--format=', '--name-only', 'HEAD', '--', 'lib'])));
  const out = {};
  for (const rel of [...ever].filter(isModule).filter((p) => !live.has(p)).sort()) {
    const blobs = new Set();
    for (const c of lines(git(repoDir, ['log', '--no-renames', '--format=%H', 'HEAD', '--', rel]))) {
      let blob;
      try { blob = git(repoDir, ['rev-parse', '--verify', '-q', `${c}:${rel}`]).trim(); } catch (e) { continue; }   // the deleting commit
      if (blob) blobs.add(blob);
    }
    const shas = new Set([...blobs].map((b) => crypto.createHash('sha256').update(git(repoDir, ['cat-file', 'blob', b], true)).digest('hex')));
    if (shas.size) out[rel] = [...shas].sort();
  }
  return out;
}

function render(table) {
  return [
    "'use strict';",
    '/**',
    ' * B-259: runtime modules the package once shipped and no longer does, with the sha256',
    ' * of every blob each path held in Git history. `lib/runtime.js` retires an unrecorded',
    ' * runtime file (older than `.managed.json`) only when its bytes match one of these',
    ' * exactly; edited or foreign files stay. Generated by `node scripts/retired-runtime.js',
    ' * --write`; `test/runtime_retired_test.js` regenerates it and fails on any difference.',
    ' */',
    '',
    `const BLOBS = ${JSON.stringify(table, null, 2).replace(/"/g, "'")};`,
    '',
    'module.exports = { BLOBS };',
    '',
  ].join('\n');
}

if (require.main === module) {
  const root = path.resolve(__dirname, '..');
  const table = generate(root);
  if (process.argv.includes('--write')) {
    fs.writeFileSync(path.join(root, 'lib', 'runtime-retired.js'), render(table));
    console.log(`lib/runtime-retired.js: ${Object.keys(table).length} path(s)`);
  } else {
    console.log(JSON.stringify(table, null, 2));
  }
}

module.exports = { generate, render };
